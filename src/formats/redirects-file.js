import { mapTemplate } from '../pattern.js';
import { isGone, prepare, skipped } from './shared.js';

const CLOUDFLARE_LIMITS = { static: 2000, dynamic: 100 };

/**
 * Netlify and Cloudflare Pages share the `_redirects` syntax: `source destination status`,
 * with `:name` placeholders and a single trailing `*` that is written back as `:splat`.
 * Returns null when the template cannot be expressed that way.
 */
function placeholderTemplate(rule, wildcardToken) {
  let supported = true;
  const text = mapTemplate(rule.template, (token, { index, name }) => {
    if (index !== undefined) {
      const label = rule.names[index - 1];
      if (label === undefined) {
        supported = false;
        return token;
      }
      return label === null ? wildcardToken : `:${label}`;
    }
    return name === 'splat' ? wildcardToken : token;
  });
  return supported ? text : null;
}

/** `*` is only allowed once, at the very end of the path. */
function wildcardAtEnd(path) {
  const count = path.split('*').length - 1;
  return count === 0 || (count === 1 && path.endsWith('*'));
}

function patternLine(rule, base) {
  if (rule.kind === 'regex') return { skip: 'REGEX_NOT_SUPPORTED' };
  if (isGone(rule)) return { skip: 'GONE_NOT_SUPPORTED' };
  if (!wildcardAtEnd(rule.path)) return { skip: 'WILDCARD_POSITION' };
  const template = placeholderTemplate(rule, ':splat');
  if (template === null) return { skip: 'NAMED_GROUP' };
  const source = rule.host === base.host ? rule.path : `https://${rule.host}${rule.path}`;
  return { line: `${source}  ${template}  ${rule.status}` };
}

/**
 * @param {import('../analyze.js').Report} report
 * @param {'netlify' | 'cloudflare'} variant
 * @returns {import('./shared.js').GeneratedFile}
 */
export function generateRedirectsFile(report, variant) {
  const { exact, patterns, base } = prepare(report);
  const notes = [];
  const staticLines = [];
  const dynamicLines = [];

  for (const rule of exact) {
    if (rule.search) notes.push(skipped(rule, 'QUERY_NOT_SUPPORTED'));
    else if (rule.to === null) notes.push(skipped(rule, 'GONE_NOT_SUPPORTED'));
    else staticLines.push(`${rule.path}  ${rule.to}  ${rule.status}`);
  }
  for (const rule of patterns) {
    const rendered = patternLine(rule, base);
    if (rendered.skip) notes.push(skipped(rule, rendered.skip));
    else dynamicLines.push(rendered.line);
  }

  if (variant === 'cloudflare') {
    for (const [kind, lines] of [
      ['static', staticLines],
      ['dynamic', dynamicLines],
    ]) {
      if (lines.length > CLOUDFLARE_LIMITS[kind]) {
        notes.push({
          code: 'LIMIT_EXCEEDED',
          line: null,
          params: { kind, limit: CLOUDFLARE_LIMITS[kind], count: lines.length },
        });
      }
    }
  }

  const text = ['# Generated by redirect-map', ...staticLines, ...dynamicLines].join('\n');
  return { text, notes, filename: '_redirects', mime: 'text/plain' };
}
