import { escapeRegex } from '../pattern.js';
import {
  MAX_BACKREFERENCES,
  decodedSource,
  dropQuery,
  isGone,
  numberedTemplate,
  prepare,
  quoteIf,
  skipped,
} from './shared.js';

const rewriteFlags = (status, target) => {
  const flags = [`R=${status}`, 'L'];
  if (/[%#]/.test(target)) flags.push('NE');
  return `[${flags.join(',')}]`;
};

function exactRule({ decoded, search, to, status }, ignoreTrailingSlash) {
  let path = decoded.replace(/^\//, '');
  if (ignoreTrailingSlash) path = path.replace(/\/+$/, '');
  const pattern = `^${escapeRegex(path)}${ignoreTrailingSlash && path ? '/?' : ''}$`;
  const lines = [];
  if (search) lines.push(`RewriteCond %{QUERY_STRING} ^${escapeRegex(search.slice(1))}$`);

  if (to === null) {
    lines.push(`RewriteRule ${quoteIf(pattern)} - [G,L]`);
  } else {
    const target = dropQuery(to);
    lines.push(
      `RewriteRule ${quoteIf(pattern)} ${quoteIf(target)} ${rewriteFlags(status, target)}`,
    );
  }
  return lines;
}

/** In a .htaccess file the pattern is matched against the path without its leading slash. */
function patternRule(rule, ignoreTrailingSlash) {
  if (rule.groupCount > MAX_BACKREFERENCES) return { skip: 'TOO_MANY_GROUPS' };
  const source = decodedSource(rule, ignoreTrailingSlash);
  if (!source.startsWith('^/')) return { skip: 'REGEX_NOT_ANCHORED' };
  const pattern = `^${source.slice(2)}`;

  if (isGone(rule)) return { line: `RewriteRule ${quoteIf(pattern)} - [G,L]` };
  const template = numberedTemplate(rule);
  if (template === null) return { skip: 'NAMED_GROUP' };
  const target = dropQuery(template);
  return {
    line: `RewriteRule ${quoteIf(pattern)} ${quoteIf(target)} ${rewriteFlags(rule.status, target)}`,
  };
}

/**
 * Apache `.htaccess` using mod_rewrite.
 * @param {import('../analyze.js').Report} report
 * @returns {import('./shared.js').GeneratedFile}
 */
export function generateApache(report) {
  const { exact, patterns, ignoreTrailingSlash } = prepare(report);
  const notes = [];
  const lines = [
    '# Generated by redirect-map',
    '# Place above other rewrite rules (for WordPress, above "# BEGIN WordPress").',
    '<IfModule mod_rewrite.c>',
    'RewriteEngine On',
  ];

  const ordered = [...exact.filter((rule) => rule.search), ...exact.filter((rule) => !rule.search)];
  for (const rule of ordered) lines.push(...exactRule(rule, ignoreTrailingSlash));

  for (const rule of patterns) {
    const rendered = patternRule(rule, ignoreTrailingSlash);
    if (rendered.skip) notes.push(skipped(rule, rendered.skip));
    else lines.push(rendered.line);
  }
  lines.push('</IfModule>');

  return { text: lines.join('\n'), notes, filename: 'redirects.htaccess', mime: 'text/plain' };
}
