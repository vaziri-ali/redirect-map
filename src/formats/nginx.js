import {
  MAX_BACKREFERENCES,
  decodedSource,
  dropQuery,
  isGone,
  numberedTemplate,
  prepare,
  skipped,
} from './shared.js';

const UNSAFE_IN_STRING = /[\s"'\\$;{}#]/;

const quoted = (text) => `"${text.replaceAll('"', '\\"')}"`;

const mapBlock = (variable, key, entries) =>
  [
    `map ${key} ${variable} {`,
    '    default "";',
    ...entries.map(([from, value]) => `    ${quoted(from)} ${quoted(value)};`),
    '}',
  ].join('\n');

/** Both spellings of a path when trailing slashes are ignored. */
function slashVariants(path, ignoreTrailingSlash) {
  if (!ignoreTrailingSlash || path === '/') return [path];
  const bare = path.replace(/\/+$/, '');
  return [bare, `${bare}/`];
}

function collectExact(exact, ignoreTrailingSlash) {
  const byPath = [];
  const byQuery = [];
  const notes = [];

  for (const rule of exact) {
    const target = rule.to ?? '';
    const value = `${rule.status}${target ? ` ${target}` : ''}`;
    const usable = !UNSAFE_IN_STRING.test(rule.decoded + rule.path + rule.search + target);
    if (!usable) {
      notes.push(skipped(rule, 'UNSAFE_CHARACTERS'));
    } else if (rule.search) {
      for (const path of slashVariants(rule.path, ignoreTrailingSlash)) {
        byQuery.push([`${path}${rule.search}`, value]);
      }
    } else {
      for (const path of slashVariants(rule.decoded, ignoreTrailingSlash)) {
        byPath.push([path, value]);
      }
    }
  }
  return { byPath, byQuery, notes };
}

function patternDirective(rule, ignoreTrailingSlash) {
  if (rule.groupCount > MAX_BACKREFERENCES) return { skip: 'TOO_MANY_GROUPS' };
  const regex = quoted(decodedSource(rule, ignoreTrailingSlash));
  if (isGone(rule)) return { block: `location ~ ${regex} { return 410; }` };

  const template = numberedTemplate(rule);
  if (template === null) return { skip: 'NAMED_GROUP' };
  if (rule.status === 301 || rule.status === 302) {
    const flag = rule.status === 301 ? 'permanent' : 'redirect';
    return { rewrite: `rewrite ${regex} ${dropQuery(template)} ${flag};` };
  }
  return { block: `location ~ ${regex} { return ${rule.status} ${template}; }` };
}

/**
 * Nginx: exact rules become `map` lookups, wildcard and regex rules become `rewrite`
 * directives (or `location` blocks for status codes `rewrite` cannot produce).
 *
 * @param {import('../analyze.js').Report} report
 * @returns {import('./shared.js').GeneratedFile}
 */
export function generateNginx(report) {
  const { exact, patterns, ignoreTrailingSlash } = prepare(report);
  const { byPath, byQuery, notes } = collectExact(exact, ignoreTrailingSlash);
  const rewrites = [];
  const locations = [];

  for (const rule of patterns) {
    const directive = patternDirective(rule, ignoreTrailingSlash);
    if (directive.skip) notes.push(skipped(rule, directive.skip));
    else if (directive.rewrite) rewrites.push(directive.rewrite);
    else locations.push(directive.block);
  }

  const lookup = (variable) =>
    `if ($${variable} ~ "^(?<rmcode>\\d{3}) ?(?<rmto>.*)$") { return $rmcode $rmto; }`;
  const http = [
    '# Generated by redirect-map',
    '# 1) http {} context, for example conf.d/redirects.conf',
  ];
  if (byPath.length) http.push(mapBlock('$rm_path', '$uri', byPath));
  if (byQuery.length) http.push(mapBlock('$rm_query', '$request_uri', byQuery));

  const server = ['# 2) server {} context, then: nginx -t && nginx -s reload'];
  if (byQuery.length) server.push(lookup('rm_query'));
  if (byPath.length) server.push(lookup('rm_path'));
  server.push(...rewrites);
  if (locations.length) {
    server.push('', '# location blocks for status codes rewrite cannot emit', ...locations);
  }

  return {
    text: [...http, '', ...server].join('\n'),
    notes,
    filename: 'redirects.nginx.conf',
    mime: 'text/plain',
  };
}
